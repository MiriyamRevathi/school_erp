  private recordAuditLog(recordId: string, action: LearningOutcomeTaxonomyAuditAction, user: string, prev?: any, curr?: any): void {
    this.auditLogs.push({
      auditId: `AUDIT_$LEARNING_OUTCOME_TAXONOMY_${Date.now()}_${Math.floor(Math.random() * 1000)}`,
      recordId,
      action,
      performedBy: user,
      timestamp: new Date().toISOString(),
      previousState: prev,
      newState: curr,
      changeSummary: `Action ${action} executed on record ${recordId} in domain module learning_outcome_taxonomy`,
    });
  }

